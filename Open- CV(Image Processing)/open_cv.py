#Using the pixel manipulation (Average method)
#This method converts an image to grayscale by averaging the contributions of color channels (RGB). It’s a simple approach but not very accurate because it treats all colors equally, ignoring how the human eye perceives brightness.

import cv2
import os
from google.colab.patches import cv2_imshow

# Fallback file path targeting a verified image in the workspace
img_path = 'C:\\Documents\\full_path\\tomatoes.jpg'
if not os.path.exists(img_path):
    img_path = 'car.jpg'

img = cv2.imread(img_path)

if img is None:
    raise FileNotFoundError("Could not find or load the target image 'car.jpg'!")

rows, cols = img.shape[:2]

for i in range(rows):
    for j in range(cols):
        # Convert values to int to prevent overflow when summing channels
        gray = (int(img[i, j, 0]) + int(img[i, j, 1]) + int(img[i, j, 2])) // 3
        img[i, j] = [gray, gray, gray]

print("Grayscale Image (Average Method):")
cv2_imshow(img)

#Weighted Method (Recommended)
#This method uses standard luminance weights (0.2989R + 0.5870G + 0.1140B) to account for human visual sensitivity—more to green, less to red, least to blue. It produces a more realistic and visually accurate grayscale image.

import cv2
import os
from google.colab.patches import cv2_imshow

# Fallback file path targeting a verified image in the workspace
img_path = 'C:\\Documents\\full_path\\tomatoes.jpg'
if not os.path.exists(img_path):
    img_path = 'car.jpg'

img_weighted = cv2.imread(img_path)

if img_weighted is None:
    raise FileNotFoundError("Could not find or load the target image 'car.jpg'!")

rows, cols = img_weighted.shape[:2]

for i in range(rows):
    for j in range(cols):
        # BGR representation in OpenCV: index 2 = Red, 1 = Green, 0 = Blue
        gray = 0.2989 * int(img_weighted[i, j][2]) + 0.5870 * int(img_weighted[i, j][1]) + 0.1140 * int(img_weighted[i, j][0])
        img_weighted[i, j] = [int(gray), int(gray), int(gray)]

print("Grayscale Image (Weighted Method):")
cv2_imshow(img_weighted)

