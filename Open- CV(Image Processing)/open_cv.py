import cv2
import easyocr
from google.colab.patches import cv2_imshow
import os
img = cv2.imread("/content/gdrive/My Drive/Colab Notebooks/jpg/car10.jpg")
if img is None:
    raise FileNotFoundError("Image not found. Upload 'cars (1).jpg' first!")

gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY);

# Detect license plates using the previously loaded cascade classifier
plates = plate_cascade.detectMultiScale(gray,scaleFactor=1.1,minNeighbors=4,minSize=(25, 25))
reader = easyocr.Reader(['en'])
print("Detected License Plates and Extracted Text:")
for (x, y, w, h) in plates:
    # Draw rectangle around the detected plate
    cv2.rectangle(img, (x, y), (x+w, y+h), (0, 255, 0), 2)
    cv2.putText(img, "Number Plate", (x, y-10),
                cv2.FONT_HERSHEY_SIMPLEX, 0.7,
                (0, 255, 0), 2)

    # Crop the license plate region
    cropped_plate = img[y:y+h, x:x+w]

    # Convert the cropped plate to grayscale for OCR if easyocr expects it
    # Although easyocr can handle color, grayscale might sometimes improve results
    cropped_plate_gray = cv2.cvtColor(cropped_plate, cv2.COLOR_BGR2GRAY)

    # Perform OCR on the cropped plate
    text_results = reader.readtext(cropped_plate_gray)

    detected_texts = [text for (bbox, text, prob) in text_results]
    if detected_texts:
        print(f"  Plate at ({x},{y},{w},{h}): {', '.join(detected_texts)}")
    else:
        print(f"  Plate at ({x},{y},{w},{h}): No text detected")

# Display the image with detected plates
cv2_imshow(img)

